-- =========================================================
-- FUNÇÃO PRINCIPAL DE VALIDAÇÃO
-- =========================================================

create or replace function public.validate_loyalty_order(
  p_order_number bigint,
  p_customer_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_stamp_count integer;
  v_reward_exists boolean;
begin

  -- Busca e bloqueia o pedido durante a validação.
  select *
  into v_order
  from public.orders
  where order_number = p_order_number
  for update;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'ORDER_NOT_FOUND',
      'message', 'Pedido não encontrado.'
    );
  end if;

  -- O pedido precisa pertencer ao cliente.
  if v_order.customer_id <> p_customer_id then
    return jsonb_build_object(
      'success', false,
      'code', 'ORDER_NOT_OWNED',
      'message', 'Este pedido não pertence ao cliente.'
    );
  end if;

  -- Somente pedido recebido gera carimbo.
  if v_order.status <> 'received' then
    return jsonb_build_object(
      'success', false,
      'code', 'ORDER_NOT_RECEIVED',
      'message', 'O pedido ainda não está elegível para carimbo.'
    );
  end if;

  -- Proteção adicional contra reutilização.
  if exists (
    select 1
    from public.loyalty_stamps
    where order_id = v_order.id
  ) then
    return jsonb_build_object(
      'success', false,
      'code', 'STAMP_ALREADY_GRANTED',
      'message', 'Este pedido já gerou um carimbo.'
    );
  end if;

  -- Cria exatamente um carimbo.
  insert into public.loyalty_stamps (
    customer_id,
    order_id
  )
  values (
    p_customer_id,
    v_order.id
  );

  -- Quantidade total de carimbos.
  select count(*)
  into v_stamp_count
  from public.loyalty_stamps
  where customer_id = p_customer_id;

  -- A cada conjunto completo de 8 carimbos,
  -- verifica se existe recompensa correspondente.
  select count(*) >= floor(v_stamp_count / 8.0)
  into v_reward_exists
  from public.loyalty_rewards
  where customer_id = p_customer_id
    and status in ('available', 'redeemed');

  if mod(v_stamp_count, 8) = 0
     and not v_reward_exists then

    insert into public.loyalty_rewards (
      customer_id,
      status
    )
    values (
      p_customer_id,
      'available'
    );

  end if;

  return jsonb_build_object(
    'success', true,
    'code', 'STAMP_GRANTED',
    'message', 'Carimbo adicionado com sucesso.',
    'stamp_count', v_stamp_count,
    'card_progress', mod(v_stamp_count, 8),
    'reward_unlocked', mod(v_stamp_count, 8) = 0
  );

exception
  when unique_violation then
    return jsonb_build_object(
      'success', false,
      'code', 'STAMP_ALREADY_GRANTED',
      'message', 'Este pedido já gerou um carimbo.'
    );
end;
$$;

-- =========================================================
-- VALIDAÇÃO POR PEDIDO + TELEFONE
-- =========================================================

create or replace function public.validate_loyalty_order_by_phone(
  p_order_number bigint,
  p_phone text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id uuid;
  v_normalized_phone text;
begin
  -- Remove espaços, parênteses, hífens e qualquer caractere não numérico.
  v_normalized_phone := regexp_replace(p_phone, '\D', '', 'g');

  select o.customer_id
  into v_customer_id
  from public.orders o
  inner join public.customers c
    on c.id = o.customer_id
  where o.order_number = p_order_number
    and regexp_replace(c.phone, '\D', '', 'g') = v_normalized_phone
  limit 1;

  if v_customer_id is null then
    return jsonb_build_object(
      'success', false,
      'code', 'ORDER_NOT_FOUND',
      'message', 'Pedido não encontrado ou telefone não confere.'
    );
  end if;

  return public.validate_loyalty_order(
    p_order_number,
    v_customer_id
  );
end;
$$;

-- =========================================================
-- CONSULTA DO STATUS DA FIDELIDADE
-- =========================================================

create or replace function public.get_loyalty_status_by_phone(
  p_order_number bigint,
  p_phone text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id uuid;
  v_normalized_phone text;
  v_stamp_count integer;
  v_available_rewards integer;
  v_card_progress integer;
begin
  v_normalized_phone := regexp_replace(p_phone, '\D', '', 'g');

  select o.customer_id
  into v_customer_id
  from public.orders o
  join public.customers c
    on c.id = o.customer_id
  where o.order_number = p_order_number
    and regexp_replace(c.phone, '\D', '', 'g') = v_normalized_phone
  limit 1;

  if v_customer_id is null then
    return jsonb_build_object(
      'success', false,
      'code', 'CUSTOMER_NOT_FOUND',
      'message', 'Pedido não encontrado ou telefone não confere.'
    );
  end if;

  select count(*)
  into v_stamp_count
  from public.loyalty_stamps
  where customer_id = v_customer_id;

  select count(*)
  into v_available_rewards
  from public.loyalty_rewards
  where customer_id = v_customer_id
    and status = 'available';

  v_card_progress := mod(v_stamp_count, 8);

  return jsonb_build_object(
    'success', true,
    'code', 'LOYALTY_STATUS',
    'stamp_count', v_stamp_count,
    'card_progress', v_card_progress,
    'available_rewards', v_available_rewards,
    'reward_available', v_available_rewards > 0
  );
end;
$$;

