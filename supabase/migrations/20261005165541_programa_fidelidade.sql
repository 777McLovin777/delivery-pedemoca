create extension if not exists pgcrypto;

-- =========================================================
-- CLIENTES
-- =========================================================

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null unique,
  email text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================================================
-- PEDIDOS
-- =========================================================

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint not null unique,
  customer_id uuid not null
    references public.customers(id)
    on delete restrict,
  status text not null default 'pending'
    check (
      status in (
        'pending',
        'confirmed',
        'preparing',
        'out_for_delivery',
        'received',
        'cancelled',
        'refunded'
      )
    ),
  total numeric not null default 0
    check (total >= 0),
  received_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index orders_customer_id_idx
on public.orders(customer_id);

create index orders_order_number_idx
on public.orders(order_number);

-- =========================================================
-- CARIMBOS
-- =========================================================

create table public.loyalty_stamps (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null
    references public.customers(id)
    on delete restrict,
  order_id uuid not null
    references public.orders(id)
    on delete restrict,
  created_at timestamptz not null default now(),

  constraint loyalty_stamps_one_per_order
    unique (order_id)
);

create index loyalty_stamps_customer_id_idx
on public.loyalty_stamps(customer_id);

-- =========================================================
-- RECOMPENSAS
-- =========================================================

create table public.loyalty_rewards (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null
    references public.customers(id)
    on delete restrict,
  status text not null default 'available'
    check (
      status in (
        'available',
        'redeemed',
        'cancelled'
      )
    ),
  earned_at timestamptz not null default now(),
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create index loyalty_rewards_customer_id_idx
on public.loyalty_rewards(customer_id);

-- =========================================================
-- RATE LIMIT
-- =========================================================

create table public.loyalty_rate_limits (
  id bigint generated by default as identity primary key,
  identifier text not null,
  action text not null,
  created_at timestamptz not null default now(),

  constraint loyalty_rate_limits_action_check
    check (action in ('validate', 'status'))
);

create index loyalty_rate_limits_lookup_idx
on public.loyalty_rate_limits (
  identifier,
  action,
  created_at
);

