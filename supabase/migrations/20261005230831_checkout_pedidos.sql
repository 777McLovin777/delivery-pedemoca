create table public.order_items (
  id uuid primary key default gen_random_uuid(),

  order_id uuid not null
    references public.orders(id)
    on delete cascade,

  product_id text not null,

  product_name text not null,

  unit_price numeric(10, 2) not null
    check (unit_price >= 0),

  quantity integer not null
    check (quantity > 0),

  customization jsonb not null default '{}'::jsonb,

    observation text
    check (
      observation is null
      or char_length(observation) <= 150
    ),

  line_total numeric(10, 2) not null
    check (line_total >= 0),

  created_at timestamptz not null default now()
);


create index order_items_order_id_idx
  on public.order_items(order_id);

  -- =========================================================
-- REGRAS DE INTEGRIDADE DO CHECKOUT
-- =========================================================

alter table public.orders
  add constraint orders_fulfillment_data_check
  check (
    fulfillment_type is null
    or
    (
      fulfillment_type = 'delivery'
      and delivery_neighborhood_id is not null
      and delivery_address is not null
      and btrim(delivery_address) <> ''
      and delivery_number is not null
      and btrim(delivery_number) <> ''
      and pickup_location_id is null
    )
    or
    (
      fulfillment_type = 'pickup'
      and pickup_location_id is not null
      and delivery_neighborhood_id is null
      and delivery_address is null
      and delivery_number is null
    )
  );

alter table public.orders
  add constraint orders_checkout_total_check
  check (
    checkout_version is null
    or total = subtotal + delivery_fee
  );

alter table public.orders
  add constraint orders_payment_data_check
  check (
    (
      payment_method = 'pix'
      and cash_given is null
      and change_amount is null
    )
    or
    (
      payment_method = 'cash'
      and (
        (
          cash_given is null
          and change_amount is null
        )
        or
        (
          cash_given >= total
          and change_amount = cash_given - total
        )
      )
    )
  );

