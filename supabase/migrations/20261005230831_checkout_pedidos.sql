alter table public.orders
  add column subtotal numeric(10, 2) not null default 0
    check (subtotal >= 0),

  add column delivery_fee numeric(10, 2) not null default 0
    check (delivery_fee >= 0),

  add column fulfillment_type text
    check (
      fulfillment_type is null
      or fulfillment_type in ('delivery', 'pickup')
    ),

  add column delivery_neighborhood_id bigint
    references public.delivery_neighborhoods(id)
    on delete restrict,

  add column delivery_address text,

  add column delivery_number text,

  add column delivery_complement text,

  add column delivery_reference text,

  add column delivery_neighborhood_name text,

  add column pickup_location_id bigint
    references public.pickup_locations(id)
    on delete restrict,

  add column payment_method text
    check (payment_method in ('pix', 'cash')),

  add column cash_given numeric(10, 2)
    check (cash_given >= 0),

  add column change_amount numeric(10, 2)
    check (change_amount >= 0),

  add column estimated_at timestamptz,

    add column checkout_token uuid,

  add column checkout_version integer;


create unique index orders_checkout_token_idx
  on public.orders(checkout_token)
  where checkout_token is not null;

  alter table public.orders
  add constraint orders_checkout_version_check
  check (
    checkout_version is null
    or checkout_version = 1
  );


alter table public.orders
  add constraint orders_checkout_required_data_check
  check (
    checkout_version is null
    or (
      checkout_version = 1
      and checkout_token is not null
      and fulfillment_type is not null
      and payment_method is not null
      and estimated_at is not null
    )
  );

create index orders_delivery_neighborhood_id_idx
  on public.orders(delivery_neighborhood_id);


create index orders_pickup_location_id_idx
  on public.orders(pickup_location_id);

